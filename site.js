const languageOrder = ["en", "zhHans", "zhHant", "ja", "ko"];
let currentLanguage = "en";
const currentView = document.body.dataset.initialView || "home";

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function getInitialLanguage() {
  const requested = new URL(window.location.href).searchParams.get("lang");
  if (translations[requested]) return requested;
  const stored = localStorage.getItem("pocketcass-language");
  if (translations[stored]) return stored;
  const browserLanguage = navigator.language.toLowerCase();
  if (browserLanguage.startsWith("zh-tw") || browserLanguage.startsWith("zh-hk") || browserLanguage.startsWith("zh-mo")) return "zhHant";
  if (browserLanguage.startsWith("zh")) return "zhHans";
  if (browserLanguage.startsWith("ja")) return "ja";
  if (browserLanguage.startsWith("ko")) return "ko";
  return "en";
}

function htmlLanguage(language) {
  if (language === "zhHans") return "zh-Hans";
  if (language === "zhHant") return "zh-Hant";
  return language;
}

function renderSections(sections) {
  return `<div class="section-list">${sections.map(([title, body], index) => `
    <section class="paper-section">
      <span class="index">${String(index + 1).padStart(2, "0")}</span>
      <div><h2>${escapeHtml(title)}</h2><p>${escapeHtml(body)}</p></div>
    </section>
  `).join("")}</div>`;
}

function render() {
  const copy = translations[currentLanguage] || translations.en;
  const content = document.querySelector("#pageContent");
  const card = document.querySelector("#contentPanel");

  document.documentElement.lang = htmlLanguage(currentLanguage);
  document.querySelectorAll("[data-copy]").forEach((node) => { node.textContent = copy[node.dataset.copy]; });
  document.querySelectorAll("[data-view-link]").forEach((link) => {
    const view = link.dataset.viewLink;
    link.classList.toggle("is-active", view === currentView);
    const file = view === "home" ? "index.html" : `${view}.html`;
    link.href = `${file}?lang=${currentLanguage}`;
  });

  if (currentView === "home") {
    document.title = "PocketCass";
    content.innerHTML = `
      <div class="home-layout">
        <div class="home-copy">
          <p class="eyebrow">POCKETCASS</p>
          <h1 class="page-heading">${escapeHtml(copy.homeTitle)}</h1>
          <p class="page-lead">${escapeHtml(copy.homeLead)}</p>
        </div>
        <img class="home-player" src="assets/player.png" alt="${escapeHtml(copy.playerImageAlt)}" width="230" height="357">
      </div>`;
  } else {
    const isPrivacy = currentView === "privacy";
    const title = isPrivacy ? copy.privacyTitle : copy.supportTitle;
    const lead = isPrivacy ? copy.privacyLead : copy.supportLead;
    const sections = isPrivacy ? copy.privacySections : copy.supportSections;
    document.title = `${title} — PocketCass`;
    content.innerHTML = `
      <header class="paper-heading">
        <p class="eyebrow">POCKETCASS</p>
        <h1 class="page-heading">${escapeHtml(title)}</h1>
        <p class="page-lead">${escapeHtml(lead)}</p>
        ${isPrivacy ? `<div class="meta">${escapeHtml(copy.updated)}</div>` : ""}
      </header>
      ${renderSections(sections)}`;
  }

  card.classList.remove("is-changing");
  void card.offsetWidth;
  card.classList.add("is-changing");
}

const languageSelect = document.querySelector("#languageSelect");
languageOrder.forEach((language) => {
  const option = document.createElement("option");
  option.value = language;
  option.textContent = translations[language].langName;
  languageSelect.append(option);
});

currentLanguage = getInitialLanguage();
languageSelect.value = currentLanguage;
languageSelect.addEventListener("change", () => {
  currentLanguage = languageSelect.value;
  localStorage.setItem("pocketcass-language", currentLanguage);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", currentLanguage);
  window.history.replaceState({}, "", url);
  render();
});

render();
